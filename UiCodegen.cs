using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace DboAssetsStudio;

// Turns an approved .uilayout.json into a C++ header for the client:
// layout constants (rects, colours, fonts) plus a Build() that creates the
// components with NtlGui exactly as rendered by ui-render.exe. Game logic
// stays in the hand-written window class; geometry comes only from here.
internal static class UiCodegen
{
    public static object Generate(string layoutPath, string outHeader, bool allowUnapproved)
    {
        var status = UiRenderService.Status(layoutPath);
        bool approved = (bool)status.GetType().GetProperty("approved")!.GetValue(status)!;
        if (!approved && !allowUnapproved) throw new InvalidOperationException("The layout is not approved (or it changed after approval). Generate the review with 'ui review', get an OK and record it with 'ui approve'. For tests only: --allow-unapproved.");
        var layout = UiLayout.Load(layoutPath);
        var scene = layout.Resolve("default", includeHidden: true);
        string ns = "UiLayout_" + Regex.Replace(layout.Name, @"[^A-Za-z0-9]+(.)?", m => m.Groups[1].Value.ToUpperInvariant());
        ns = Regex.Replace(ns, "^UiLayout_([a-z])", m => "UiLayout_" + m.Groups[1].Value.ToUpperInvariant());
        string hash = UiRenderService.LayoutHash(layoutPath);

        // Group id0..idN of the same type into arrays.
        var groups = new List<(string Name, List<UiComponent> Items, bool Array)>();
        var used = new HashSet<string>();
        foreach (var c in scene.Components)
        {
            if (used.Contains(c.Id) || (c.Type == "group" && !c.Clip)) continue;
            var m = Regex.Match(c.Id, @"^(.*?)(\d+)$");
            if (m.Success && m.Groups[2].Value == "0")
            {
                string b = m.Groups[1].Value; var items = new List<UiComponent>();
                for (int i = 0; ; i++) { var n = scene.Components.FirstOrDefault(x => x.Id == b + i.ToString(CultureInfo.InvariantCulture) && x.Type == c.Type); if (n == null) break; items.Add(n); }
                if (items.Count > 1) { foreach (var it in items) used.Add(it.Id); groups.Add((b.TrimEnd('_'), items, true)); continue; }
            }
            used.Add(c.Id); groups.Add((c.Id, [c], false));
        }

        var h = new StringBuilder();
        // Interpolated strings must be fully built first: StringBuilder's handler writes while evaluating,
        // and TexExpr() emits declarations of its own.
        void Emit(string line) => h.AppendLine(line);
        Emit($"// Generated by: dbo-assets ui codegen {Path.GetFileName(layoutPath)}");
        Emit($"// Layout hash {hash}{(approved ? " (approved)" : " (NOT APPROVED - test only)")}. Do not edit: change the layout, review, approve, regenerate.");
        h.AppendLine("#pragma once");
        h.AppendLine("#include \"gui_precomp.h\"");
        h.AppendLine("#include \"gui_dialog.h\"\n#include \"gui_panel.h\"\n#include \"gui_staticbox.h\"\n#include \"gui_button.h\"\n#include \"gui_flash.h\"");
        h.AppendLine("#include \"Gui/HudEmbeddedArt.h\"");
        h.AppendLine();
        Emit($"namespace {ns}");
        h.AppendLine("{");
        Emit($"\tstatic const int DIALOG_W = {scene.DialogWidth}, DIALOG_H = {scene.DialogHeight};");
        h.AppendLine("\tstruct Rect { int x, y, w, h; };");
        foreach (var g in groups)
        {
            string id = Cpp(g.Name);
            var c0 = g.Items[0];
            if (g.Array) Emit($"\tstatic const Rect {id}[{g.Items.Count}] = {{ {string.Join(", ", g.Items.Select(R))} }};");
            else Emit($"\tstatic const Rect {id} = {R(c0)};");
            if (c0.Type is "label" or "button" or "input" || c0.Text != null)
                Emit($"\tstatic const int {id}_FONT = {c0.FontSize}; static const int {id}_FONT_ATTR = {(c0.Bold ? 1 : 0)}; static const COLORREF {id}_COLOR = RGB({(c0.TextColor >> 16) & 255}, {(c0.TextColor >> 8) & 255}, {c0.TextColor & 255}); static const DWORD {id}_STYLE = {Style(c0)};");
        }
        h.AppendLine();
        // Component pointers.
        h.AppendLine("\tstruct Components");
        h.AppendLine("\t{");
        foreach (var g in groups)
        {
            string type = Klass(g.Items[0].Type);
            h.AppendLine(g.Array ? $"\t\t{type}* {Cpp(g.Name)}[{g.Items.Count}];" : $"\t\t{type}* {Cpp(g.Name)};");
        }
        h.AppendLine("\t};");
        h.AppendLine();
        h.AppendLine("\tinline gui::CSurface Region(gui::CTexture* tex, int x, int y, int w, int h, int sx, int sy, int sw, int sh, BYTE a = 255, BYTE r = 255, BYTE g = 255, BYTE b = 255)");
        h.AppendLine("\t{");
        h.AppendLine("\t\tgui::CSurface s; s.m_pTexture = tex;");
        h.AppendLine("\t\tPlaneSnapShot& p = s.m_Original; p.rtRect.left = x; p.rtRect.top = y; p.rtRect.right = x + w; p.rtRect.bottom = y + h;");
        h.AppendLine("\t\tp.uAlpha = a; p.uRed = r; p.uGreen = g; p.uBlue = b;");
        h.AppendLine("\t\tif (tex) { float tw = (float)tex->GetWidth(), th = (float)tex->GetHeight(); if (sw < 0) sw = (int)tw; if (sh < 0) sh = (int)th;");
        h.AppendLine("\t\t\tp.UVs[0] = sx / tw; p.UVs[1] = sy / th; p.UVs[2] = (sx + sw) / tw; p.UVs[3] = (sy + sh) / th; }");
        h.AppendLine("\t\ts.m_SnapShot = p; return s;");
        h.AppendLine("\t}");
        h.AppendLine();
        h.AppendLine("\t// Creates every component of the layout inside pDialog. Textures loaded here are owned by the caller (list returned in textures).");
        h.AppendLine("\tinline void Build(gui::CDialog* pDialog, gui::CSurfaceManager* pSurf, Components& out, std::vector<gui::CTexture*>& textures)");
        h.AppendLine("\t{");
        h.AppendLine("\t\tmemset(&out, 0, sizeof(out));");
        h.AppendLine("\t\tCRectangle rc;");
        var texVars = new Dictionary<string, string>();
        var notes = new List<string>();
        string TexExpr(UiImage? img)
        {
            if (img?.File is null) return "NULL";
            if (texVars.TryGetValue(img.File, out var v)) return v;
            v = "tex" + texVars.Count.ToString(CultureInfo.InvariantCulture); texVars[img.File] = v;
            string f = img.File;
            if (f.StartsWith("embedded:", StringComparison.OrdinalIgnoreCase)) Emit($"\t\tgui::CTexture* {v} = LoadEmbeddedHudArt(\"{f[9..]}\"); if ({v}) textures.push_back({v});");
            else if (f.StartsWith("gui:", StringComparison.OrdinalIgnoreCase)) Emit($"\t\tgui::CTexture* {v} = pSurf->CreateSurface(\"{f[4..].Replace("\\", "\\\\")}\").m_pTexture;");
            else
            {
                string name = Path.GetFileName(f.StartsWith("pak:", StringComparison.OrdinalIgnoreCase) ? f.Split('|').Last() : f);
                notes.Add($"{name}: new image; embed it with scripts/embed-hud-art.py (or copy it to texture\\gui) and change the asset to embedded:/gui:.");
                Emit($"\t\tgui::CTexture* {v} = LoadEmbeddedHudArt(\"{name}\"); if ({v}) textures.push_back({v}); // TODO: new asset, embed it first");
            }
            return v;
        }
        string Surf(UiImage? img, int w, int hh, uint fill)
        {
            if (img == null) return $"Region(NULL, 0, 0, {w}, {hh}, 0, 0, 0, 0, {fill >> 24}, {(fill >> 16) & 255}, {(fill >> 8) & 255}, {fill & 255})";
            string t = img.File == null ? "NULL" : TexExpr(img);
            int[] d = img.Dest ?? [0, 0, w, hh];
            return $"Region({t}, {d[0]}, {d[1]}, {d[2]}, {d[3]}, {img.SrcX}, {img.SrcY}, {img.SrcWidth}, {img.SrcHeight}, {img.Tint >> 24}, {(img.Tint >> 16) & 255}, {(img.Tint >> 8) & 255}, {img.Tint & 255})";
        }
        List<UiImage> AllImages(UiComponent c) { var l = new List<UiImage>(); if (c.Image != null) l.Add(c.Image); l.AddRange(c.Images); return l; }
        // Parent per component: the nearest clipping container (a child CDialog), else the window.
        var parentOf = scene.Components.ToDictionary(x => x.Id, x => x.Parent);
        var clipVar = new Dictionary<string, (string Var, int X, int Y)>();
        (string Var, int X, int Y) ParentFor(UiComponent c)
        {
            for (string? p = c.Parent; p != null; p = parentOf.GetValueOrDefault(p)) if (clipVar.TryGetValue(p, out var v)) return v;
            return ("pDialog", 0, 0);
        }
        string FontName(UiComponent c) => c.Font.Equals("Default", StringComparison.OrdinalIgnoreCase) ? "DEFAULT_FONT" : $"(CHAR*)\"{c.Font}\"";
        foreach (var g in groups)
        {
            string id = Cpp(g.Name);
            for (int i = 0; i < g.Items.Count; i++)
            {
                var c = g.Items[i];
                string rectRef = g.Array ? $"{id}[{i}]" : id, target = g.Array ? $"out.{id}[{i}]" : $"out.{id}";
                var par = ParentFor(c);
                Emit(par.Var == "pDialog" ? $"\t\trc.SetRectWH({rectRef}.x, {rectRef}.y, {rectRef}.w, {rectRef}.h);" : $"\t\trc.SetRectWH({rectRef}.x - {par.X}, {rectRef}.y - {par.Y}, {rectRef}.w, {rectRef}.h);");
                var imgs = AllImages(c);
                switch (c.Type)
                {
                    case "group":
                        // Clipping container: children are created inside it and clipped to its rect.
                        Emit($"\t\t{target} = NTL_NEW gui::CDialog(rc, {par.Var}, pSurf);{(par.Var != "pDialog" ? $" {target}->SetClippingMode(true);" : "")}");
                        break;
                    case "panel": case "icon": case "progress": case "scroll": case "input":
                        if (imgs.Count > 0 || (c.Fill >> 24) != 0) Emit($"\t\t{target} = NTL_NEW gui::CPanel(rc, {par.Var}, pSurf, {Surf(imgs.FirstOrDefault(), c.Width, c.Height, c.Fill)});");
                        else Emit($"\t\t{target} = NTL_NEW gui::CPanel(rc, {par.Var}, pSurf);");
                        foreach (var extra in imgs.Skip(1)) Emit($"\t\t{target}->AddSurface({Surf(extra, c.Width, c.Height, 0)});");
                        if (c.Type is "progress" or "scroll") notes.Add($"{c.Id}: {c.Type} is generated as a background panel; the window code updates the bar/thumb.");
                        break;
                    case "label":
                        Emit($"\t\t{target} = NTL_NEW gui::CStaticBox(rc, {par.Var}, pSurf, {id}_STYLE);");
                        Emit($"\t\t{target}->CreateFontStd({FontName(c)}, {id}_FONT, {id}_FONT_ATTR); {target}->SetTextColor({id}_COLOR);");
                        foreach (var bg in imgs) Emit($"\t\t{target}->AddSurface({Surf(bg, c.Width, c.Height, 0)});");
                        if (c.Shadow) Emit($"\t\t{target}->SetEffectMode(TE_SHADOW);");
                        if (!string.IsNullOrEmpty(c.Text)) Emit($"\t\t{target}->SetText(L\"{W(c.Text)}\"); // sample text from the layout");
                        break;
                    case "button":
                        Emit($"\t\t{target} = NTL_NEW gui::CButton(rc, std::wstring(L\"{W(c.Text ?? "")}\"), {par.Var}, pSurf);");
                        Emit($"\t\t{target}->SetTextFont({FontName(c)}, {id}_FONT, {id}_FONT_ATTR); {target}->SetTextStyle({id}_STYLE); {target}->SetTextUpColor({id}_COLOR); {target}->SetTextFocusColor({id}_COLOR);");
                        if (imgs.Count == 0 && (c.Fill >> 24) != 0) Emit($"\t\t{target}->AddSurfaceUp({Surf(null, c.Width, c.Height, c.Fill)});");
                        foreach (var up in imgs) Emit($"\t\t{target}->AddSurfaceUp({Surf(up, c.Width, c.Height, 0)});");
                        foreach (var state in new[] { "focus", "down", "disabled" })
                        {
                            string slot = state switch { "focus" => "Focus", "down" => "Down", _ => "Disabled" };
                            var list = c.StateImageLists.TryGetValue(state, out var sl) ? sl : c.StateImages.TryGetValue(state, out var si) && si != null ? [si] : [];
                            foreach (var img in list) Emit($"\t\t{target}->AddSurface{slot}({Surf(img, c.Width, c.Height, 0)});");
                        }
                        break;
                    case "flash":
                    {
                        string swf = c.File == null ? "" : c.File.StartsWith("flash:", StringComparison.OrdinalIgnoreCase) ? c.File[6..] : Path.GetFileName(c.File);
                        if (c.File != null && !c.File.StartsWith("flash:", StringComparison.OrdinalIgnoreCase)) notes.Add($"{swf}: new movie; add it to flash.pak as flash\\{Path.GetFileNameWithoutExtension(swf)}\\{swf}.");
                        Emit($"\t\t{target} = NTL_NEW gui::CFlash(rc, {par.Var}, pSurf, \"{swf}\", TRUE);");
                        if (c.Frame >= 0) Emit($"\t\t{target}->GotoFrame({c.Frame});");
                        break;
                    }
                }
                if (par.Var != "pDialog" && c.Type != "group") Emit($"\t\t{target}->SetClippingMode(true);");
                if (c.Hidden) Emit($"\t\t{target}->Show(false); // hidden: the window code shows it");
                if (c.Clip) clipVar[c.Id] = (target, c.X, c.Y);
            }
        }
        h.AppendLine("\t}");
        h.AppendLine("}");
        if (notes.Count > 0) { h.AppendLine(); foreach (var n in notes.Distinct()) h.AppendLine("// NOTE: " + n); }
        outHeader = ContentSafety.SafeOutput(outHeader);
        Directory.CreateDirectory(Path.GetDirectoryName(outHeader)!);
        File.WriteAllText(outHeader, h.ToString().Replace("\r\n", "\n"), new UTF8Encoding(true));
        return new { header = outHeader, @namespace = ns, layoutHash = hash, approved, components = scene.Components.Count, notes = notes.Distinct().ToArray() };
    }

    static string R(UiComponent c) => $"{{ {c.X}, {c.Y}, {c.Width}, {c.Height} }}";
    static string Cpp(string id) => Regex.IsMatch(id, "^[A-Za-z_]") ? id : "_" + id;
    static string Klass(string type) => type switch { "label" => "gui::CStaticBox", "button" => "gui::CButton", "flash" => "gui::CFlash", "group" => "gui::CDialog", _ => "gui::CPanel" };
    static int Style(UiComponent c) => (c.Align switch { "center" => 0x08, "right" => 0x10, _ => 0x04 }) | (c.VAlign switch { "top" => 0, "up" => 0x20, "bottom" => 0x80, _ => 0x40 });
    static string W(string s)
    {
        var sb = new StringBuilder();
        foreach (char ch in s) sb.Append(ch switch { '"' => "\\\"", '\\' => "\\\\", '\n' => "\\n", _ when ch < 32 || ch > 126 => $"\\x{(int)ch:X4}\" L\"", _ => ch.ToString() });
        return sb.ToString();
    }
}
